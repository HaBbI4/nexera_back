package services

import "errors"

// Сигнальные ошибки защиты публичных форм (заявки, отзывы) от спама. Хендлер отвечает на них
// так, чтобы клиент не узнал, какая именно проверка сработала.
var (
	// ErrSpamDetected — заполнено honeypot-поле: запрос отправил бот. Хендлер отвечает
	// успехом, ничего не сохранив, — чтобы бот не понял, что его отсекли.
	ErrSpamDetected = errors.New("spam detected")

	// ErrDuplicateSubmission — заявка/отзыв с тем же телефоном уже были недавно (окно
	// задается в конфиге). Хендлер отвечает 429 "попробуйте позже", не уточняя причину.
	ErrDuplicateSubmission = errors.New("duplicate submission")
)
